// ─── Prompt Builder ─────────────────────────────────────────────────────────

export function buildCareerTranslatorPrompt(
  resumeJson: string,
  targetIndustry: string,
  targetRole: string,
): string {
  let prompt = careerTranslatorPrompt;

  prompt += "\n\n# 用户当前简历\n\n" + resumeJson + "\n";
  prompt += "\n# 目标行业\n\n" + targetIndustry + "\n";
  prompt += "\n# 目标岗位\n\n" + targetRole + "\n";
  prompt += "\n请基于以上信息生成跨行业翻译方案，严格返回 JSON。\n";
  return prompt;
}
