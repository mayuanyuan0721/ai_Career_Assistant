// ─── Prompt Builder ─────────────────────────────────────────────────────────

export function buildInterviewPrepPrompt(
  resumeJson: string,
  jd?: string,
  industry?: string,
): string {
  let prompt = interviewPrepPrompt;

  prompt += "\n\n# 用户简历\n\n" + resumeJson + "\n";

  if (jd) {
    prompt += "\n# 目标岗位 JD\n\n" + jd + "\n";
  }

  if (industry) {
    prompt += "\n# 目标行业\n\n" + industry + "\n";
  }

  prompt += "\n请基于以上信息生成面试准备材料，严格返回 JSON。\n";
  return prompt;
}
